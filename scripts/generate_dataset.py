# Add project root to path
sys.path.append(str(Path(__file__).resolve().parent.parent))

from utils.expert_dataset import ExpertDataset, ExpertDatasetWriter, replay_validate_episode
from utils.scripted_expert import ExpertConfig, ObjectProfile

logger = logging.getLogger("generate_dataset")
logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)s | %(name)s | %(message)s")


def load_config(path: str) -> Dict[str, Any]:
    with open(path, "r") as f:
        return yaml.safe_load(f)


def compute_file_hash(filepath: str, algo: str = "sha1") -> str:
    h = hashlib.new(algo)
    with open(filepath, "rb") as f:
        while True:
            chunk = f.read(8192)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def worker_loop_fn(
    worker_id: int,
    cfg: Dict[str, Any],
    result_queue: mp.Queue,
    shard_seed: int,
    samples_per_worker: int,
):
    """Worker process entry point."""
    try:
        logger.info(f"[Worker {worker_id}] starting with seed {shard_seed}, target samples: {samples_per_worker}")
        expert_config = ExpertConfig(**cfg.get("expert_config", {}))
        object_profile = ObjectProfile(
            size=np.array(cfg["object_size"], dtype=np.float32),
            grasp_width_normalized=cfg["grasp_width"]
        )

        # --- CRITICAL BUG FIX ---
        # Remove the repeated keyword argument
        ds = ExpertDataset(
            urdf_path=cfg["urdf_path"],
            env_xml_path=cfg["xml_path"],
            base_seed=shard_seed,
            # Use the correct, single argument for the sample limit
            max_samples_per_epoch=samples_per_worker,
            action_scaling_factor=cfg["action_scaling_factor"],
            scripted_cfg=ExpertConfig(**cfg.get("expert_config", {})),
            object_size=tuple(np.array(cfg["object_size"]).tolist()),
            object_grasp_width=cfg["grasp_width"],
            yield_full_obs=False,
            # Make warmup configurable from the YAML
            warmup=cfg.get("warmup", True)
        )

        # Consume the entire iterator for this worker.
        # The dataset will stop automatically when it hits its sample limit.
        pbar = tqdm(total=samples_per_worker, desc=f"Worker {worker_id}", leave=False)
        for _ in ds:
            pbar.update(1)
        pbar.close()

        # After iteration, collect the episodes generated by this worker's instance.
        worker_eps = ds.episodes
        logger.info(f"[Worker {worker_id}] finished. Collected {len(worker_eps)} successful episodes.")
        result_queue.put(worker_eps)

    except Exception as e:
        logger.error(f"[Worker {worker_id}] encountered exception: {e}", exc_info=True)
        result_queue.put([])

def merge_worker_episodes(all_eps: List[List[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    merged = []
    for eps in all_eps:
        merged.extend(eps)
    return merged


def replay_filter(episodes: List[Dict[str, Any]], cfg: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Optionally filter out episodes whose replay mismatch is too large.
    """
    validated = []
    tol = cfg.get("replay_tol", 0.03)
    for ep in episodes:
        ok = replay_validate_episode(ep, cfg["urdf_path"], cfg["xml_path"])
        if ok:
            validated.append(ep)
        else:
            logger.warning(f"Dropping episode id={ep.get('episode_id')} due to replay mismatch")
    return validated


def main():
    parser = argparse.ArgumentParser(description="Production dataset generation")
    parser.add_argument("--config", type=str, required=True, help="YAML config file path")
    parser.add_argument("--resume_path", type=str, default=None, help="Path to existing dataset to resume from")
    args = parser.parse_args()

    cfg = load_config(args.config)
    out_dir = Path(cfg["output_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)

    logger.info("Loaded config:")
    for k, v in cfg.items():
        logger.info(f"  {k}: {v}")

    # Prepare metadata fields
    dataset_writer = ExpertDatasetWriter(out_dir=cfg["output_dir"], run_name=cfg.get("run_name", None))
    dataset_writer.metadata = {
        "config": cfg,
        "urdf_hash": compute_file_hash(cfg["urdf_path"]) if Path(cfg["urdf_path"]).exists() else None,
        "xml_hash": compute_file_hash(cfg["xml_path"]) if Path(cfg["xml_path"]).exists() else None,
        "git_commit": None  # if you integrate git info via subprocess
    }

    total_samples_target = cfg["num_samples"]
    num_workers = cfg.get("num_workers", 0)
    shard_idx = cfg.get("shard_idx", 0)
    num_shards = cfg.get("num_shards", 1)

    # Determine seed offset per worker/shard
    base_seed = cfg.get("seed", 0)
    shard_seed_base = base_seed + shard_idx * cfg.get("shard_seed_offset", 1000000)

    if num_workers > 0:
        manager = mp.Manager()
        result_queue: mp.Queue = manager.Queue()
        samples_per_worker = (total_samples_target + num_workers - 1) // num_workers

        processes = []
        for w in range(num_workers):
            # Compute per-worker seed
            seed_w = shard_seed_base + w * cfg.get("worker_seed_offset", 10000)
            p = mp.Process(target=worker_loop_fn, args=(w, cfg, result_queue, seed_w, samples_per_worker))
            p.start()
            processes.append(p)

        # Collect episodes from workers
        worker_eps_all: List[List[Dict[str, Any]]] = []
        for w in range(num_workers):
            eps = result_queue.get()
            worker_eps_all.append(eps)

        # Join
        for p in processes:
            p.join()

        collected = merge_worker_episodes(worker_eps_all)

    else:
        # --- FINAL PATCH 3 of 3: Clean up single-threaded logic ---
        logging.info("Running in single-threaded mode.")
        expert_config = ExpertConfig(**cfg.get("expert_config", {}))
        object_profile = ObjectProfile(
            size=np.array(cfg["object_size"], dtype=np.float32),
            grasp_width_normalized=cfg["grasp_width"]
        )
        ds = ExpertDataset(
            urdf_path=cfg["urdf_path"],
            env_xml_path=cfg["xml_path"],
            base_seed=base_seed + shard_idx,
            max_samples_per_epoch=total_samples_target,
            action_scaling_factor=cfg["action_scaling_factor"],
            scripted_cfg=expert_config,
            object_size=tuple(object_profile.size.tolist()),
            object_grasp_width=object_profile.grasp_width_normalized,
            yield_full_obs=False,
            warmup=cfg.get("warmup", True)
        )
        
        # Iterate directly over the dataset for cleanliness and efficiency.
        # tqdm shows progress based on samples yielded.
        with tqdm(total=total_samples_target, desc="Generating Samples") as pbar:
            for _ in ds:
                pbar.update(1)

        collected = ds.episodes


    logger.info(f"Collected {len(collected)} episodes before filtering")

    # Replay validation if enabled
    if cfg.get("do_replay_validate", True):
        validated = replay_filter(collected, cfg)
    else:
        validated = collected

    logger.info(f"{len(validated)} episodes remain after replay validation")

    if not validated:
        logger.error("No episodes to save after validation. Aborting.")
        return

    dataset_writer.episodes = validated
    dataset_writer.metadata.update({
        "num_episodes": len(validated),
        "timestamp": time.time(),
    })
    dataset_writer.save()

    logger.info("Dataset generation complete.")


if __name__ == "__main__":
    main()
