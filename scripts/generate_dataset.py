#!/usr/bin/env python3
"""
generate_dataset.py

Production-grade dataset generation script. Features:

- YAML-config-driven
- Multiprocessing-friendly aggregation across workers (using Manager queues or LMDB shards)
- Checkpointing & resume support
- Shard support across multiple runs
- Replay validation of episodes
- Balanced sampling / filtering hooks
- Metadata logging (URDF hash, git commit, config snapshot, environment hash)
- Progress bar and worker-level logging

Usage:
    python generate_dataset.py --config configs/gen_dataset.yaml
    python scripts/generate_dataset.py --config configs/gen_dataset_config.yaml

"""

from __future__ import annotations
import os
import sys
import time
import yaml
import logging
import hashlib
import json
