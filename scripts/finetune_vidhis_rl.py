    def _create_history_obs_space(self, obs_space: DictSpace, history_len: int) -> DictSpace:
        history_spaces = {}
        for key, space in obs_space.spaces.items():
            history_shape = (history_len,) + space.shape
            history_spaces[key] = Box(
                low=np.repeat(space.low[np.newaxis, ...], history_len, axis=0),
                high=np.repeat(space.high[np.newaxis, ...], history_len, axis=0),
                shape=history_shape, dtype=space.dtype
            )
        
        ### FIX A.1: ADD THE SUBGOAL TO THE BUFFER'S OBSERVATION SPACE ###
        # The subgoal is a single image, not a history.
        subgoal_space = obs_space.spaces['image_primary']
        history_spaces['subgoal_image'] = Box(
            low=subgoal_space.low,
            high=subgoal_space.high,
            shape=subgoal_space.shape, # No history dimension
            dtype=subgoal_space.dtype
        )
        return DictSpace(history_spaces)

    def _build_single_env(self, rank: int, is_eval: bool = False) -> gym.Env:
        env_cfg = self.cfg.environment
        seed = self.cfg.seed + rank + (1000 if is_eval else 0)
        env = PandaEnv(control_mode=env_cfg.control_mode, render_mode="rgb_array")
        
        # --- Apply SOTA Reward Wrapper ---
