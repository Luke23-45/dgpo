    def _build_models_and_optimizers(self):
        log.info("--- Building Hierarchical RL Models ---")
        

        # --- 2. Build Controller (Actor) ---
        proprio_dim = self.expert_loader.dataset.get_proprioception_dim()
        ctrl_cfg = self.cfg.model.controller
        policy_kwargs = {
            "proprio_dim": proprio_dim, **ctrl_cfg,
            "scheduler_cfg": NoiseSchedulerConfig(**self.cfg.scheduler), "device": self.device
        }
