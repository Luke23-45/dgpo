"""
A state-of-the-art, research-grade Reinforcement Learning fine-tuning script for the
hierarchical ViDHiS system. This implementation is designed for maximum performance,
robustness, and reproducibility, incorporating advanced techniques to solve the
limitations of pure Behavior Cloning (BC).

The core of this script is a Hierarchical TD3+BC algorithm, which fine-tunes a
pre-trained DiffusionPolicy (the Controller/Actor) conditioned on visual subgoals
generated by a frozen, pre-trained VisualPlannerDiffusion (the Planner).

Key Architectural & Algorithmic Advancements:
  - **Hierarchical TD3+BC:** Adapts the powerful TD3+BC algorithm for a hierarchical
    policy structure. It grounds the high-level planning of the Planner in the
    low-level, reactive control learned by the Controller, solving the open-loop
    execution and freezing failures observed in pure BC.

  - **Subgoal-Conditioned Critic:** A novel Twin Critic architecture that learns a
    value function Q(s, g_sub, a), enabling it to evaluate actions in the context
    of the current visual subgoal provided by the Planner. This is essential for
    learning multi-stage tasks.

  - **Representation Sharing:** The Critic leverages the powerful, pre-trained
    vision encoders from the Actor (DiffusionPolicy). This dramatically improves
    sample efficiency and training stability by grounding the value function in a
    rich, pre-learned feature space.

  - **Dense, Shaped Rewards:** Integrates the `AdvancedRewardWrapperV2`, which
    provides a dense, potential-based reward signal. This is the critical
    supervisory signal that enables the Critic to learn a meaningful value
    landscape and guide the Actor toward successful, non-brittle behaviors.

  - **Robust Engineering:**
    - **Hydra Configuration:** For complete and modular experiment management.
    - **Platform-Aware Vectorized Environments:** Automatically selects the most
      stable VecEnv implementation (SubprocVecEnv vs. DummyVecEnv) based on the OS.
    - **Atomic Checkpointing:** Saves checkpoints to a temporary file and uses
      `os.replace` to prevent corruption from interruptions. Saves full training
      state, including RNG, for perfect resumption.
    - **Decoupled Evaluation:** Uses parallel environments for efficient statistics
      gathering and a separate, single environment for clean video rendering,
      avoiding common VecEnv rendering issues.
    - **Comprehensive Logging:** Deep integration with TensorBoard and Weights &
      Biases, including system metrics, video uploads, and configuration tracking.
"""

