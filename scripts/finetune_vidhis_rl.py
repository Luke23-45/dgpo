def set_seed(seed: int):
    """Sets the seed for all relevant random number generators for maximum reproducibility."""
    os.environ["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8" # For deterministic CUDA ops
    torch.manual_seed(seed)
    np.random.seed(seed)
