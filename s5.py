# FILE: scripts/compare_delta_vs_absolute.py

"""
A definitive diagnostic script to compare the delta-controlled expert trajectory
against a "ground truth" trajectory generated by the proven absolute controller.

This script:
1.  RUNS the simulation using the DELTA controller.
2.  At each step, it CALCULATES what the ABSOLUTE controller would have done.
3.  LOGS the discrepancy ("mimicry error") between the two to a CSV file.
4.  GENERATES a video of the delta-controlled attempt, with the live
    mimicry error and expert state overlaid on the frames.

If the mimicry error is consistently high, it points to a fundamental
mismatch in the controller's scaling or physics. If the error is low but the
expert still fails, it points to issues like drift or oscillation.
"""
