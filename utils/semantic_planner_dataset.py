"""
Semantic Planner Dataset.

This module defines the data pipeline for the Advantage-Weighted Semantic Planner (AWSP).
It is engineered to serve (State, Subgoal, Advantage) tuples using EXPLICIT Ground Truths
generated directly by the Expert, removing the need for post-hoc inference.

Key Features:
1.  **Explicit Supervision**: Loads 'gt_phase' and 'gt_gripper' directly from the
    recorded expert metadata, eliminating label noise from heuristic thresholding.
2.  **Stable Keyframe Targeting**: Identifies the geometric center of future phases
    to provide robust regression targets.
3.  **Advantage Integration**: Seamlessly loads pre-calculated advantage scores.
4.  **High-Performance IO**: Leverages the SOTA caching mechanisms of the
    underlying ExpertDatasetReader.
"""

from __future__ import annotations

import logging
import random
from typing import Dict, List, Optional, Any

import numpy as np
import torch
from PIL import Image
from torch.utils.data import default_collate

# Import base class and reader
from utils.ego_planner_dataset import EgoPlannerDataset

# Setup logger
log = logging.getLogger(__name__)


class SemanticPlannerDataset(EgoPlannerDataset):
    """
    A specialized dataset for training the Semantic Planner.
    Uses 'gt_phase' and 'gt_gripper' directly from the expert generation.
    """

    def __init__(self, 
                 dataset_path: str, 
                 use_aug: bool = False):
        log.info(f"Initializing SemanticPlannerDataset (Explicit Oracle). Path: {dataset_path}")
        
        # Initialize base class. We set obs_horizon=1 as the planner is Markovian.
        # action_horizon=1 is a dummy value required by the reader but unused here.
        super().__init__(
            dataset_path=dataset_path,
            obs_horizon=1,
            action_horizon=1,
            use_aug=use_aug
        )
        
        # --- SOTA VALIDATION (Explicit Keys) ---
        if self.expert_reader.get_num_episodes() > 0:
            first_ep_meta = self.expert_reader.episode_metadata[0]
            modalities = first_ep_meta["modalities"]
            
            # Check for the NEW keys generated by the updated Expert
            required_keys = ["advantages", "gt_phase", "gt_gripper", "ee_pose_world", "actions", "proprio"]
            missing_keys = [key for key in required_keys if key not in modalities]
            
            if missing_keys:
                raise RuntimeError(
                    f"Dataset at {dataset_path} is missing required modalities: {missing_keys}. "
                    "Ensure you regenerated data with the updated 'scripted_expert.py' and ran 'advantage_calculator.py'."
                )
        
        log.info("Dataset loaded. Ready for AWR training with Explicit Labels.")

    def _find_next_subgoal_pose(self, 
                                current_t: int, 
                                task_phases: np.ndarray, 
                                ee_poses: np.ndarray) -> np.ndarray:
        """
        Identifies the 'Stable Keyframe' of the next phase using explicit labels.
        
        Logic:
        1. Identify current semantic phase from GT labels.
        2. Scan forward to find when the label changes.
        3. Target the 80% mark of that next phase segment for stability.
        """
        # Cast to standard int array to avoid tensor/scalar mismatches
        task_phases = task_phases.flatten().astype(np.int32)
        current_phase = task_phases[current_t]
        
        # Slice forward to find the transition
        future_phases = task_phases[current_t + 1:]
        
        # Find indices where phase != current
        transition_indices = np.where(future_phases != current_phase)[0]
        
        if len(transition_indices) == 0:
            # No future transition -> We are in the final approach to goal.
            # Target the final frame.
            return ee_poses[-1]

        # Start of next phase (Relative Index)
        phase_start_rel = transition_indices[0]
        target_phase_val = future_phases[phase_start_rel]
        
        # Find where the NEXT phase ends (to determine duration/stability)
        next_future_slice = future_phases[phase_start_rel:]
        next_transitions = np.where(next_future_slice != target_phase_val)[0]
        
        if len(next_transitions) > 0:
            phase_len = next_transitions[0]
        else:
            phase_len = len(next_future_slice)
            
        # Target 80% into the phase for maximum grasp stability
        offset = int(phase_len * 0.8)
        
        # Convert back to absolute episode index
        target_t = (current_t + 1) + phase_start_rel + offset
        target_t = min(target_t, len(ee_poses) - 1)
        
        return ee_poses[target_t]

    def __getitem__(self, idx: int) -> Optional[Dict[str, Any]]:
        """
        Retrieves a training sample using Explicit Ground Truths.
        """
        if not (0 <= idx < len(self)):
            raise IndexError(f"Index {idx} out of range.")

        try:
            # 1. Resolve Index using Parent Logic
            ep_idx, timestep_t = self.samples[idx]
            ep_meta = self.expert_reader.episode_metadata[ep_idx]

            # 2. Helper for Fast Access
            def get_mod(name):
                meta = ep_meta["modalities"][name]
                return self.expert_reader._get_full_modality_array(
                    key=meta["key"], compression=meta["compression"],
                    dtype_str=meta["dtype"], shape_list=tuple(meta["shape"])
                )

            # 3. Load Data Modalities
            # Note: These calls are cached by the reader, so this is efficient.
            all_images = get_mod("image_primary")
            all_poses = get_mod("ee_pose_world")
            all_advantages = get_mod("advantages")
            all_proprio = get_mod("proprio")
            
            # Load Explicit Ground Truths (Generated by Expert)
            all_gt_phases = get_mod("gt_phase")
            all_gt_grippers = get_mod("gt_gripper")

            # 4. Extract Inputs
            initial_image_np = all_images[0]
            goal_image_np = all_images[-1]
            
            # Input: Use Explicit Phase (Scalar)
            current_phase_val = int(all_gt_phases[timestep_t].item())
            
            # Input: Proprioception
            current_proprio_np = all_proprio[timestep_t]

            # 5. Extract Targets
            
            # Target A: Subgoal Pose (Using Explicit Phases for lookup)
            gt_subgoal_pose_np = self._find_next_subgoal_pose(timestep_t, all_gt_phases, all_poses)
            
            # Target B: Gripper State (Direct from Expert Logic)
            # 1.0 = Closed/Grasp intent, 0.0 = Open intent
            gt_gripper_state_val = float(all_gt_grippers[timestep_t].item())
            
            # Weight: Advantage
            advantage_val = all_advantages[timestep_t]

            # 6. Visual Transforms & Augmentation
            initial_image_pil = Image.fromarray(initial_image_np)
            goal_image_pil = Image.fromarray(goal_image_np)

            if self.use_aug:
                # SOTA: Apply independent jitter to force robust feature matching
                if random.random() < self.aug_random_apply_p:
                    initial_image_pil = self.aug_color_jitter(initial_image_pil)
                if random.random() < self.aug_random_apply_p:
                    goal_image_pil = self.aug_color_jitter(goal_image_pil)

            initial_image_tensor = self.transform_primary(initial_image_pil)
            goal_image_tensor = self.transform_primary(goal_image_pil)

            # 7. Assemble Output Dictionary
            # We use torch.tensor() with copy logic implicitly to ensure writability and thread safety.
            return {
                # Inputs
                'initial_image': initial_image_tensor.float(),
                'goal_image': goal_image_tensor.float(),
                'task_phase': torch.tensor(current_phase_val, dtype=torch.long),
                'current_proprio': torch.tensor(current_proprio_np, dtype=torch.float32),
                
                # Targets
                'ground_truth_subgoal_pose': torch.tensor(gt_subgoal_pose_np, dtype=torch.float32),
                'ground_truth_gripper_state': torch.tensor([gt_gripper_state_val], dtype=torch.float32),
                
                # Meta
                'advantage': torch.tensor([advantage_val], dtype=torch.float32)
            }

        except Exception as e:
            log.error(f"Error loading sample {idx} (Ep {ep_idx}, T {timestep_t}): {e}", exc_info=False)
            return None


def semantic_planner_collate_fn(batch: List[Optional[Dict[str, Any]]]) -> Dict[str, Any]:
    """
    Robust collation function that filters out failed samples (None) 
    to prevent crashing the entire training batch.
    """
    valid_samples = [s for s in batch if s is not None]
    if not valid_samples: 
        log.warning("Batch collation failed: All samples were None.")
        return {}
    return default_collate(valid_samples)